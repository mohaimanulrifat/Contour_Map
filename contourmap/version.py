"""Version and environment information shown in About and 'Copy version info'."""
import platform
import sys

VERSION = "1.0.0"


def build_date() -> str:
    """Date the release was built (written by the build script), or 'from source'."""
    try:
        from . import build_info          # generated by tools/write_build_info.py
        return build_info.BUILD_DATE
    except Exception:
        return "from source"


def _pkg_version(name: str) -> str:
    try:
        from importlib import metadata
        return metadata.version(name)
    except Exception:
        return "unknown"


def components() -> dict:
    """The main parts inside this copy, with versions."""
    return {
        "Python": platform.python_version(),
        "matplotlib": _pkg_version("matplotlib"),
        "SciPy": _pkg_version("scipy"),
        "pandas": _pkg_version("pandas"),
        "NumPy": _pkg_version("numpy"),
    }


def os_description() -> str:
    if sys.platform == "win32":
        ver = platform.version()
        try:
            build = int(ver.split(".")[-1])
        except ValueError:
            build = 0
        name = "Windows 11" if build >= 22000 else "Windows 10" if ver.startswith("10.") else "Windows"
        return f"{name} (build {ver}), {platform.machine() or 'unknown'}"
    return f"{platform.system()} {platform.release()}, {platform.machine()}"


def version_info_text(app_name: str) -> str:
    """Plain text to paste into a problem report. Contains no personal data."""
    lines = [f"{app_name} {VERSION} (built {build_date()})", os_description()]
    lines += [f"{k} {v}" for k, v in components().items()]
    return "\n".join(lines)
